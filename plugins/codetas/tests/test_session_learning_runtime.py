    def test_named_profile_from_transcript_can_write(self) -> None:
        jsonl = self.state / f"rollout-{SESSION}.jsonl"
        lines = [
            record(
                "session_meta",
                {
                    "base_instructions": {
                        "developer_instructions": "CODETAS-LEARNING-ORIGIN\nCODETAS-LEARNING-PROFILE:named:scyther\n"
                    }
                },
            )
        ]
        for index in range(6):
            lines.append(
                record(
                    "response_item",
                    {
                        "type": "message",
                        "role": "user",
                        "content": [{"type": "input_text", "text": f"turn {index}"}],
                    },
                )
            )
        jsonl.write_text(
            "".join(json.dumps(item) + "\n" for item in lines),
            encoding="utf-8",
        )

        def fake_review(state, cursor, review):
            from profile_learning import memory_tool

            written = memory_tool(state.get("scope_token"), "add", "memory", "User prefers terse reports.")
            return {"ok": True, "writes": 1 if written.get("success") else 0}

        with patch("session_learning_runtime.run_review", side_effect=fake_review):
            result = step_session(SESSION, jsonl, ending=False)
        self.assertTrue(result.get("reviewed"))
        self.assertEqual(result.get("kind"), "named")
        self.assertEqual(result.get("profile_name"), "scyther")
        memory = (self.profile / "memories" / "MEMORY.md").read_text(encoding="utf-8")
        self.assertIn("User prefers terse reports.", memory)

